/* Function Name:
 *      l2sw_setAsicPortUnknownDaBehavior
 * Description:
 *      Set UNDA behavior
 * Input:
 *      port        - port ID
 *      behavior    - 0: flooding to unknwon DA portmask; 1: drop; 2:trap; 3: flooding
 * Output:
 *      None
 * Return:
 *      L2SW_ERR_OK           - Success
 *      L2SW_ERR_SMI          - SMI access error
 *      L2SW_ERR_NOT_ALLOWED  - Invalid behavior
 * Note:
 *      None
 */
ret_t l2sw_setAsicPortUnknownDaBehavior(l2sw_uint8 units, l2sw_uint32 port, l2sw_uint32 behavior)
{
    if(port >= L2SW_PORTNO)
        return L2SW_ERR_PORT_ID;

    if(behavior >= L2_UNDA_BEHAVE_END)
        return L2SW_ERR_NOT_ALLOWED;

    if(port < 8)
        return l2sw_setAsicRegBits(units, L2SW_REG_UNKNOWN_UNICAST_DA_PORT_BEHAVE, L2SW_Port0_ACTION_MASK << (port * 2), behavior);
    else
        return l2sw_setAsicRegBits(units, L2SW_REG_UNKNOWN_UNICAST_DA_PORT_BEHAVE_EXT, L2SW_PORT8_ACTION_MASK << ((port-8) * 2), behavior);
}
