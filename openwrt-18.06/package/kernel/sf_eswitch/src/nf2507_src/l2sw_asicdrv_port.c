                    return retVal;


                if ((retVal = l2sw_setAsicRegBit(units, 0x1d41, 5, 0)) != L2SW_ERR_OK)
                    return retVal;
                if ((retVal = l2sw_setAsicRegBit(units, 0x1d41, 7, 0)) != L2SW_ERR_OK)
                    return retVal;


                if ((retVal = l2sw_setAsicRegBits(units, 0x1d95, 3, 0)) != L2SW_ERR_OK)
                    return retVal;


