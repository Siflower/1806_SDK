/* Function Name:
 *      l2sw_getAsicPortForceLink
 * Description:
 *      Get port force linking configuration
 * Input:
 *      port        - Physical port number (0~7)
 *      pPortAbility - port ability configuration
 * Output:
 *      None
 * Return:
 *      L2SW_ERR_OK       - Success
 *      L2SW_ERR_SMI      - SMI access error
 *      L2SW_ERR_PORT_ID  - Invalid port number
 * Note:
 *      None
 */
ret_t l2sw_getAsicPortForceLink(l2sw_uint8 units, l2sw_uint32 port, l2sw_port_ability_t *pPortAbility)
{
    ret_t retVal;
    l2sw_uint32 regData;

    /* Invalid input parameter */
    if(port >= L2SW_PORTNO)
        return L2SW_ERR_PORT_ID;

    retVal = l2sw_getAsicReg(units, L2SW_REG_MAC0_FORCE_SELECT + port, &regData);
    if(retVal != L2SW_ERR_OK)
        return retVal;

    pPortAbility->forcemode = (regData >> 12) & 0x0001;
    pPortAbility->mstfault  = (regData >> 9) & 0x0001;
    pPortAbility->mstmode   = (regData >> 8) & 0x0001;
    pPortAbility->nway      = (regData >> 7) & 0x0001;
    pPortAbility->txpause   = (regData >> 6) & 0x0001;
    pPortAbility->rxpause   = (regData >> 5) & 0x0001;
    pPortAbility->link      = (regData >> 4) & 0x0001;
    pPortAbility->duplex    = (regData >> 2) & 0x0001;
    pPortAbility->speed     = regData & 0x0003;

    return L2SW_ERR_OK;
}
